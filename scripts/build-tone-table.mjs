// Reads the preset list of the SoundFont and writes src/data/sf2Presets.generated.ts,
// so the tone browser knows every tone before the 31 MB file itself is loaded.
//
//   node scripts/build-tone-table.mjs [path-to.sf2]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const file = process.argv[2] ?? join(root, 'public', 'soundfonts', 'GeneralUser-GS.sf2');
const buf = readFileSync(file);
const tag = (o) => buf.toString('latin1', o, o + 4);
if (tag(0) !== 'RIFF' || tag(8) !== 'sfbk') throw new Error('not a SoundFont 2 file');

let phdr = null;
for (let p = 12; p + 8 <= buf.length; ) {
  const size = buf.readUInt32LE(p + 4);
  if (tag(p) === 'LIST') {
    for (let q = p + 12; q + 8 <= p + 8 + size; ) {
      const s = buf.readUInt32LE(q + 4);
      if (tag(q) === 'phdr') phdr = { offset: q + 8, size: s };
      q += 8 + s + (s & 1);
    }
  }
  p += 8 + size + (size & 1);
}
if (!phdr) throw new Error('no preset table');

const presets = [];
for (let i = 0; i < phdr.size / 38 - 1; i++) {
  const o = phdr.offset + i * 38;
  let name = buf.toString('latin1', o, o + 20);
  name = name.slice(0, name.indexOf('\0') < 0 ? 20 : name.indexOf('\0')).trim();
  presets.push({ bank: buf.readUInt16LE(o + 22), program: buf.readUInt16LE(o + 20), name });
}
presets.sort((a, b) => a.bank - b.bank || a.program - b.program);

const lines = presets.map((p) => `  [${p.bank}, ${p.program}, ${JSON.stringify(p.name)}],`);
const out = `// GENERATED by scripts/build-tone-table.mjs — do not edit by hand.
// Preset list of public/soundfonts/GeneralUser-GS.sf2: [bank, program, name]
export const SF2_PRESETS: readonly (readonly [number, number, string])[] = [
${lines.join('\n')}
];
`;
writeFileSync(join(root, 'src', 'data', 'sf2Presets.generated.ts'), out);
console.log(`wrote ${presets.length} presets`);
